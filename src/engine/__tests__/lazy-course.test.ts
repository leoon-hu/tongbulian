    expect(courseLoaded('english-g4')).toBe(false)
    expect(courseOfKp('e4s2-06-spell')?.course.id).toBe('english-g4')
    expect(translate({ k: 'kp.e4s2-06-spell' }, 'en')).toBe("Unit 6 Let's spell")
