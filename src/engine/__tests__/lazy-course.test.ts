    expect(courseLoaded('chinese-g2')).toBe(false)
    expect(courseOfKp('c2s1-01-kedou')?.course.id).toBe('chinese-g2')
    expect(translate({ k: 'kp.c2s1-01-kedou' }, 'zh')).toBe('小蝌蚪找妈妈')
    expect(hasGenerator('c2s1-01-kedou')).toBe(false)
    expect(courseLoaded('chinese-g3')).toBe(false)
    expect(courseOfKp('c3s1-08-simaguang')?.course.id).toBe('chinese-g3')
    expect(translate({ k: 'kp.c3s1-08-simaguang' }, 'zh')).toBe('司马光')
    expect(translate({ k: 'kp.c3s1-08-simaguang' }, 'en')).toBe('Sima Guang')
    expect(hasGenerator('c3s1-08-simaguang')).toBe(false)
    expect(courseLoaded('chinese-g4')).toBe(false)
    expect(courseOfKp('c4s1-04-jingwei')?.course.id).toBe('chinese-g4')
    expect(translate({ k: 'kp.c4s1-04-jingwei' }, 'zh')).toBe('精卫填海')
    expect(translate({ k: 'kp.c4s1-04-jingwei' }, 'en')).toBe('Jingwei Fills the Sea')
    expect(hasGenerator('c4s1-04-jingwei')).toBe(false)
    expect(courseLoaded('chinese-g5')).toBe(false)
    expect(courseOfKp('c5s2-06-maodun')?.course.id).toBe('chinese-g5')
    expect(translate({ k: 'kp.c5s2-06-maodun' }, 'zh')).toBe('自相矛盾')
    expect(translate({ k: 'kp.c5s2-06-maodun' }, 'en')).toBe('The Spear and the Shield')
    expect(hasGenerator('c5s2-06-maodun')).toBe(false)
    expect(courseLoaded('english-g3')).toBe(false)
    expect(courseOfKp('e3s1-01-letters')?.course.id).toBe('english-g3')
    expect(translate({ k: 'kp.e3s1-01-letters' }, 'zh')).toBe('Unit 1 字母和发音')
    expect(translate({ k: 'kp.e3s1-01-letters' }, 'en')).toBe('Unit 1 Letters and sounds')
    expect(translate({ k: 'unit.e3s1u1' }, 'zh')).toBe('Making friends')
