// 一课的出题材料（需求 §12 D1）：纯数据，由内容包的 lessons 文件照课本填写，makers.ts 把它变成题目条目。
// 中文都只写汉字（选项前可带一个 emoji），拼音统一查内容包的拼音表（py.ts），测试保证查得到、音节数与汉字数相等。

/**
 * 一课的材料。字段都是可选的，有什么出什么；mix 决定各档出哪些模板、各占多少。模板名见 makers.ts 的 lessonItems：
 * judge（这样做对吗）、good（哪种做法是对的）、bad（哪种做法不对）、ask（问答）、cloze（儿歌填空）。
 */
export interface LessonSpec {
  /** 知识点 id */
  kp: string
  /** 课本表扬、提倡的做法（「上课时认真听讲」）：判断题答「对」，「哪种做法是对的」的正确项 */
  good?: string[]
  /** 课本提醒不要做的做法，写明错在哪（「过马路时边走边看手机」）：判断题答「不对」，「哪种做法不对」的正确项 */
  bad?: string[]
  /** 问答：「问题=答案/错/错」，选项前可带 emoji（「🇨🇳五星红旗」显示成「🇨🇳 五星红旗」，读「五星红旗」） */
  ask?: string[]
  /** 儿歌填空：「句子，挖掉的用 [ ] 括起来|干扰/干扰」（句子照课本的儿歌、顺口溜） */
  cloze?: string[]
  /** 各档的模板与权重：「judge:3 ask:3 cloze:2」（第 1 档是练习的主体，D6） */
  mix: Record<1 | 2 | 3, string>
}
