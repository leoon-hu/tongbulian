/** 英文时刻（整时 / 半时）：整时 "3 o'clock"、半时 "half past 3" */
export function formatClockEn(hour: number, minute: number): string {
  const h = ((hour + 11) % 12) + 1
  return minute === 30 ? `half past ${h}` : `${h} o'clock`
}

