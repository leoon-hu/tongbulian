/** 「分」→ ¥ 金额（只有元、角，最多一位小数）：650 → ¥6.5、500 → ¥5、50 → ¥0.5 */
export function formatMoneyEn(fen: number): string {
  const yuan = fen / 100
  return `¥${Number.isInteger(yuan) ? String(yuan) : yuan.toFixed(1)}`
}

