// ── 英文金额的格式化（中文版复用 labels.ts 里的 formatMoney）──

/** 「分」→ ¥ 金额：650 → ¥6.5、500 → ¥5、50 → ¥0.5、5 → ¥0.05、67 → ¥0.67 */
export function formatMoneyEn(fen: number): string {
  const yuan = fen / 100
  return `¥${Number.isInteger(yuan) ? String(yuan) : yuan.toFixed(fen % 10 ? 2 : 1)}`
}

